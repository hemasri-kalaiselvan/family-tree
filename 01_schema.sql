-- Family Tree: base schema (run first)
create table if not exists public.ft_trees (
  key   text primary key,
  label text not null,
  slug  text not null unique,
  sort  integer not null default 0
);

create or replace function public.ft_touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;

create table if not exists public.ft_people (
  id integer generated by default as identity primary key,
  name text not null,
  tree text not null default 'vetri' references public.ft_trees (key) on update cascade,
  nickname text, gender text,
  father_id integer references public.ft_people (id) on delete set null,
  mother_id integer references public.ft_people (id) on delete set null,
  birth_order numeric, dob text, dod text,
  life_status text not null default 'unknown',
  birth_time text, birth_place text, death_place text,
  education text, profession text, current_location text, native_place text,
  kothram text, rasi text, natchathiram text,
  phone text, email text, blood_group text,
  facebook text, instagram text, youtube text, twitter text, linkedin text,
  github text, whatsapp text, telegram text, snapchat text, threads text,
  pinterest text, website text, maps_link text, alt_phone text,
  home_address text, photo_url text, branch text,
  is_placeholder boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  death_tamil_month text, death_paksha text, death_thithi text,
  is_hidden boolean not null default false,
  home_town text,
  constraint ft_people_gender_check check (gender = any (array['male','female','other'])),
  constraint ft_people_life_status_check check (life_status = any (array['alive','deceased','unknown']))
);
drop trigger if exists ft_trg_people_touch on public.ft_people;
create trigger ft_trg_people_touch before update on public.ft_people
  for each row execute function public.ft_touch_updated_at();

create table if not exists public.ft_marriages (
  id integer generated by default as identity primary key,
  person1_id integer not null references public.ft_people (id) on delete cascade,
  person2_id integer not null references public.ft_people (id) on delete cascade,
  status text not null default 'married',
  engagement_date text, engagement_place text,
  marriage_date text, wedding_place text, end_date text,
  photo_url text, notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ft_marriages_status_check check (status = any (array['engaged','married','separated','divorced','widowed']))
);
drop trigger if exists ft_trg_marriages_touch on public.ft_marriages;
create trigger ft_trg_marriages_touch before update on public.ft_marriages
  for each row execute function public.ft_touch_updated_at();

create table if not exists public.ft_field_access (
  table_name text not null check (table_name = any (array['ft_people','ft_marriages'])),
  column_name text not null,
  min_role text not null check (min_role = any (array['public','member_basic','member_advanced'])),
  primary key (table_name, column_name)
);

create table if not exists public.ft_app_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'member_basic'
    check (role = any (array['admin','member_advanced','member_basic']))
);
